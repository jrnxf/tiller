const PHRASES = new Map(Object.entries(PHRASE_TEXT));

// What a name we do not know reads as, so the raw name never shows.
const GENERIC = "made a change";

const CARD_SLOT = "{card}";

// One recorded mutation as a short phrase, like "closed alpha-31" or
// "added a project". `card` is the card's display id, when it touched one.
export function mutationPhrase(name: string, card: string | null): string {
  const phrase = PHRASES.get(name) ?? GENERIC;
  if (phrase.includes(CARD_SLOT)) return phrase.replace(CARD_SLOT, card || "a card");
  return card ? `${phrase} on ${card}` : phrase;
}
